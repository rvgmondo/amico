type Hours = { day?: string | null; open?: string | null; close?: string | null; closed?: boolean | null }[];

/**
 * One line of opening hours from the admin's hours, with runs of equal days joined:
 * "Mon-Thu 08:00-17:00, Fri 08:00-16:00, Sat 08:00-13:00, Sun closed".
 */
export function hoursSummary(lang: Lang, hours: Hours | null | undefined): string {
  if (!hours?.length) return "";
  const d = DICT[lang].hours;
  const slot = (h: Hours[number]) => (h.closed || !h.open || !h.close ? "closed" : `${h.open}-${h.close}`);
  const runs: { from: string; to: string; slot: string }[] = [];
  for (const h of hours) {
    if (!h.day) continue;
    const s = slot(h);
    const last = runs[runs.length - 1];
    if (last && last.slot === s) last.to = h.day;
    else runs.push({ from: h.day, to: h.day, slot: s });
  }
  return runs
    .map((r) => {
      const days = r.from === r.to ? (d.days[r.from] ?? r.from) : `${d.days[r.from] ?? r.from}-${d.days[r.to] ?? r.to}`;
      return `${days} ${r.slot === "closed" ? d.closed.toLowerCase() : r.slot}`;
    })
    .join(", ");
}
